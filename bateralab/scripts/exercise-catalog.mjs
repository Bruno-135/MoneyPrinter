/** Mãos a partir do sticking: R toca em `right`, L em `left` (com acentos/fantasmas opcionais). */
function fromSticking(sticking, right, left, velocities = {}) {
  const st = sticking.replace(/[\s|]/g, "");
  const lane = (hand) =>
    [...st].map((c, i) => (c === hand ? velocities[i] ?? "x" : "-")).join("");
  const bar = { st };
  bar[right] = lane("R");
  if (left === right) {
    bar[right] = [...st].map((c, i) => (c === "R" || c === "L" ? velocities[i] ?? "x" : "-")).join("");
  } else bar[left] = lane("L");
  return bar;
}

/** Uma linha de caixa com mãos alternadas automaticamente (R, L, R, L… a cada nota). */
function reading(line, start = "R") {
  const cells = line.replace(/[\s|]/g, "");
  let hand = start;
  const st = [...cells]
    .map((c) => {
      if (c === "-" || c === ".") return "-";
      const h = hand;
      hand = hand === "R" ? "L" : "R";
      return h;
    })
    .join("");
  return { sn: cells, st };
}

/** Converte uma linha de grade de semicolcheias para fusas (resolution 16 → 32). */
const up2 = (bar) => Object.fromEntries(Object.entries(bar).map(([k, v]) => [k, [...v.replace(/[\s|]/g, "")].map((c) => c + "-").join("")]));

/** Acentua as posições dadas numa sequência de mãos tocada toda numa peça. */
function rudiment(sticking, piece, accents = []) {
  const vel = Object.fromEntries(accents.map((i) => [i, "X"]));
  return fromSticking(sticking, piece, piece, vel);
}

